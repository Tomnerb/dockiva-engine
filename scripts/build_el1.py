#!/usr/bin/env python3
"""Compile native/hvf_el1_guest.c for the guest (aarch64, freestanding) and write its
machine code to native/hvf_el1_code.h, which the hypervisor backend copies next to its
exception vector. The code must run wherever it is copied: the build refuses
relocations and any section but .text."""
import argparse
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'native/hvf_el1_guest.c'
OUTPUT = ROOT / 'native/hvf_el1_code.h'
FLAGS = ['--target=aarch64-linux-gnu', '-std=c11', '-O2', '-Wall', '-Wextra', '-Werror', '-ffreestanding', '-fno-builtin',
         '-fno-pic', '-fno-pie', '-mgeneral-regs-only', '-mno-outline-atomics', '-fno-jump-tables', '-fno-stack-protector',
         '-fno-asynchronous-unwind-tables', '-fno-unwind-tables', '-fno-exceptions', '-fno-addrsig']

def sections(elf):
    shoff, = struct.unpack_from('<Q', elf, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', elf, 0x3a)
    headers = [struct.unpack_from('<IIQQQQIIQQ', elf, shoff + i * shentsize) for i in range(shnum)]
    names = headers[shstrndx]
    def name(offset):
        start = names[4] + offset
        return elf[start:elf.index(b'\0', start)].decode()
    return [(name(h[0]), h) for h in headers]

def build(cc):
    with tempfile.TemporaryDirectory() as scratch:
        obj = Path(scratch) / 'el1.o'
        subprocess.run([cc, *FLAGS, '-I', str(ROOT / 'native'), '-c', str(SOURCE), '-o', str(obj)], check=True)
        elf = obj.read_bytes()
    found = sections(elf)
    for name, h in found:
        kind, flags, size = h[1], h[2], h[5]
        if kind in (4, 9) and size:                                       # SHT_RELA, SHT_REL
            raise SystemExit(f'build_el1: {name} has relocations; the EL1 code must be position-independent')
        if flags & 2 and size and name != '.text':                         # SHF_ALLOC
            raise SystemExit(f'build_el1: section {name} ({size} bytes); EL1 code may use .text only')
    text = next(h for name, h in found if name == '.text')
    code = elf[text[4]:text[4] + text[5]]
    symtab = next(h for name, h in found if name == '.symtab')
    strtab = found[symtab[6]][1]
    entry = None
    for i in range(symtab[5] // 24):
        st_name, _, _, _, st_value, _ = struct.unpack_from('<IBBHQQ', elf, symtab[4] + i * 24)
        start = strtab[4] + st_name
        if elf[start:elf.index(b'\0', start)] == b'el1_entry':
            entry = st_value
    if entry is None:
        raise SystemExit('build_el1: no el1_entry')
    words = struct.unpack(f'<{len(code) // 4}I', code)
    lines = ',\n'.join('    ' + ','.join(f'0x{w:08x}' for w in words[i:i + 8]) for i in range(0, len(words), 8))
    text = ('/* Generated by scripts/build_el1.py from hvf_el1_guest.c; do not edit. */\n'
            f'#define HVF_EL1_ENTRY 0x{entry:x}u\n'
            f'static const uint32_t hvf_el1_code[]={{\n{lines}}};\n')
    if not OUTPUT.exists() or OUTPUT.read_text() != text:
        OUTPUT.write_text(text)
    print(OUTPUT, f'{len(code)} bytes')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cc', default=shutil.which('cc'))
    build(parser.parse_args().cc)
